#!/usr/bin/env bash
# Build the home screen app without Gradle: aapt2 → javac → d8 → zipalign → apksigner.
# Output: launcher/build/griffin-home.apk
# Owner settings (name, weather, app name, local news) come from config/home.env; see scripts/setup.sh.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
source "$HERE/../scripts/config.sh"
need_config WEATHER_CITY WEATHER_LAT WEATHER_LON
SDK="${ANDROID_SDK_ROOT:-/opt/homebrew/share/android-commandlinetools}"
BT="$SDK/build-tools/34.0.0"
AJAR="$SDK/platforms/android-28/android.jar"
export JAVA_HOME="${JAVA_HOME:-/opt/homebrew/opt/openjdk@17/libexec/openjdk.jdk/Contents/Home}"
export PATH="$JAVA_HOME/bin:$PATH"

SRC="$HERE/app/src/main"
OUT="$HERE/build"
KS="$HERE/debug.keystore"
VERSION="${VERSION:-$(date +%s)}"

rm -rf "$OUT" && mkdir -p "$OUT/gen" "$OUT/classes" "$OUT/dex" "$OUT/owner/values"

# Owner settings → assets/config.js and the app's name. Escaping for JS and Android strings:
js() { printf '"%s"' "$(printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g')"; }
xml() { printf '%s' "$1" | sed "s/&/\&amp;/g; s/</\&lt;/g; s/>/\&gt;/g; s/\\\\/\\\\\\\\/g; s/'/\\\\'/g; s/\"/\\\\\"/g"; }
feeds="" sep=""
for f in $LOCAL_NEWS_FEEDS; do feeds+="$sep$(js "$f")"; sep=", "; done
local_news=null
[[ -n "$feeds" && -n "$LOCAL_NEWS_NAME" ]] &&
  local_news="{ name: $(js "$LOCAL_NEWS_NAME"), sub: $(js "$LOCAL_NEWS_SUB"), feeds: [$feeds] }"

cp -R "$SRC/assets" "$OUT/assets"
cat > "$OUT/assets/config.js" <<JS
// Generated by launcher/build.sh from config/home.env.
window.HOME_CONFIG = {
  name: $(js "$NAME"),
  appName: $(js "$APP_NAME"),
  city: $(js "$WEATHER_CITY"),
  place: $(js "$WEATHER_PLACE"),
  lat: $WEATHER_LAT,
  lon: $WEATHER_LON,
  tz: $(js "$WEATHER_TZ"),
  units: $(js "$([[ $UNITS == metric ]] && echo °C || echo °F)"),
  tvModel: $(js "$TV_MODEL"),
  fireOS: $(js "$FIRE_OS"),
  localNews: $local_news
};
JS
APP_XML="$(xml "$APP_NAME")"
cat > "$OUT/owner/values/strings.xml" <<XML
<?xml version="1.0" encoding="utf-8"?>
<resources>
    <string name="app_name">$APP_XML</string>
    <string name="guard_label">$APP_XML guard</string>
    <string name="guard_description">Opens $APP_XML whenever Amazon\\'s home screen appears. Also draws the volume bar. Turn off to use Amazon\\'s home.</string>
</resources>
XML

"$BT/aapt2" compile --dir "$SRC/res" -o "$OUT/res.zip"
"$BT/aapt2" compile "$OUT/owner/values/strings.xml" -o "$OUT"
# -R overlays the owner's strings on the defaults in res/values/strings.xml.
"$BT/aapt2" link -I "$AJAR" --manifest "$SRC/AndroidManifest.xml" -A "$OUT/assets" \
  --min-sdk-version 22 --target-sdk-version 28 \
  --version-code "$((VERSION / 60))" --version-name "1.0" \
  --java "$OUT/gen" -o "$OUT/unsigned.apk" "$OUT/res.zip" -R "$OUT/values_strings.arsc.flat"

javac -source 8 -target 8 -nowarn -Xlint:-options -encoding UTF-8 \
  -classpath "$AJAR" -d "$OUT/classes" \
  $(find "$SRC/java" "$OUT/gen" -name '*.java')

"$BT/d8" --lib "$AJAR" --min-api 22 --output "$OUT/dex" $(find "$OUT/classes" -name '*.class')
(cd "$OUT/dex" && zip -q -u "$OUT/unsigned.apk" classes.dex)

"$BT/zipalign" -f 4 "$OUT/unsigned.apk" "$OUT/aligned.apk"

if [[ ! -f "$KS" ]]; then
  keytool -genkeypair -keystore "$KS" -storepass android -keypass android -alias griffin \
    -keyalg RSA -keysize 2048 -validity 10000 -dname "CN=Griffin Home" >/dev/null 2>&1
fi
"$BT/apksigner" sign --ks "$KS" --ks-pass pass:android --key-pass pass:android \
  --out "$OUT/griffin-home.apk" "$OUT/aligned.apk"

echo "Built $OUT/griffin-home.apk ($APP_NAME · ${NAME:-no name} · $WEATHER_PLACE)"
